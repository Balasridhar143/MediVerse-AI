/**
 * Helper to safely extract translation with fallback
 */
export const getTranslationText = (category, key, subKey, lang = 'en') => {
  try {
    const cat = MEDICAL_TRANSLATIONS[category];
    if (!cat) return '';
    const item = cat[key];
    if (!item) return '';

    // If subKey is passed (e.g. easyMeaning or name)
    if (subKey && item[subKey]) {
      return item[subKey][lang] || item[subKey].en || '';
    }

    // Direct object
    if (item[lang]) return item[lang];
    if (item.en) return item.en;
  } catch (err) {
    console.warn('Translation lookup error:', err);
  }
  return '';
};

/**
 * Returns localized string for UI labels with English fallback
 */
export const getUiText = (key, lang = 'en') => {
  const item = MEDICAL_TRANSLATIONS.ui[key];
  if (!item) return key;
  return item[lang] || item.en || key;
};

/**
 * Returns localized meaning for clinical terms
 */
export const getTermTranslation = (termKey, lang = 'en') => {
  const termData = MEDICAL_TRANSLATIONS.terms[termKey];
  if (!termData) {
    return {
      name: termKey,
      easyMeaning: 'Medical test measurement or clinical term.',
      whyMeasured: 'Commonly measured to evaluate general metabolic or cellular health.',
      sampleResultExplanation: null,
    };
  }

  return {
    name: termData.name[lang] || termData.name.en || termKey,
    easyMeaning: termData.easyMeaning[lang] || termData.easyMeaning.en,
    whyMeasured: termData.whyMeasured?.[lang] || termData.whyMeasured?.en,
    sampleResultExplanation: termData.sampleResultExplanation?.[lang] || termData.sampleResultExplanation?.en,
  };
};

