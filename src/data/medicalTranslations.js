/**
 * Returns localized parameter metadata and explanation
 */
export const getParameterTranslation = (parameter, lang = 'en') => {
  if (!parameter) return null;
  const termKey = parameter.name || parameter.testName || '';
  
  let termData = MEDICAL_TRANSLATIONS.terms[termKey];
  if (!termData) {
    const k = termKey.toLowerCase();
    if (k.includes('hemoglobin') || k.includes('hb')) {
      termData = MEDICAL_TRANSLATIONS.terms.Hemoglobin;
    } else if (k.includes('wbc') || k.includes('white blood')) {
      termData = MEDICAL_TRANSLATIONS.terms.WBC;
    } else if (k.includes('platelet')) {
      termData = MEDICAL_TRANSLATIONS.terms.Platelets;
    } else if (k.includes('glucose') || k.includes('sugar') || k.includes('fbs')) {
      termData = MEDICAL_TRANSLATIONS.terms.Glucose;
    } else if (k.includes('creatinine')) {
      termData = MEDICAL_TRANSLATIONS.terms.Creatinine;
    } else if (k.includes('cholesterol') || k.includes('lipid')) {
      termData = MEDICAL_TRANSLATIONS.terms.Cholesterol;
    } else if (k.includes('triglyceride')) {
      termData = MEDICAL_TRANSLATIONS.terms.Triglycerides;
    } else if (k.includes('bilirubin')) {
      termData = MEDICAL_TRANSLATIONS.terms.Bilirubin;
    }
  }

  const localizedName = termData?.name?.[lang] || termData?.name?.en || parameter.name;
  const localizedMeaning = termData?.easyMeaning?.[lang] || termData?.easyMeaning?.en || parameter.easyMeaning;

  let localizedStatus = parameter.status;
  if (parameter.indicator === 'below') {
    localizedStatus = getUiText('belowRange', lang);
  } else if (parameter.indicator === 'above') {
    localizedStatus = getUiText('aboveRange', lang);
  } else if (parameter.indicator === 'within') {
    localizedStatus = getUiText('withinRange', lang);
  }

  return {
    name: localizedName,
    easyMeaning: localizedMeaning,
    status: localizedStatus,
    sampleResultExplanation: termData?.sampleResultExplanation?.[lang] || termData?.sampleResultExplanation?.en,
  };
};
